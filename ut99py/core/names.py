def _member(name: str) -> str:
    """Enum member name for a header spelling; keywords get a trailing _."""
    return f"{name}_" if keyword.iskeyword(name) else name


EName = IntEnum("EName", {_member(name): index for index, name in _HARDCODED}, module=__name__)

# Index -> header spelling (the C++ GNames[] table).
